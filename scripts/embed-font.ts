// Writes core/fonts/noto-sans-bold.ts from core/fonts/NotoSans-Bold.ttf. The priced photo's labels need
// the font file on disk wherever the app runs, and neither the agents' bundles nor Next's carry a file
// read relative to the source, so the bytes travel inside a module instead.
//   npx tsx scripts/embed-font.ts
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const font = readFileSync(resolve(process.cwd(), "core/fonts/NotoSans-Bold.ttf"));
const out = resolve(process.cwd(), "core/fonts/noto-sans-bold.ts");
writeFileSync(
  out,
  `// Generated by scripts/embed-font.ts from core/fonts/NotoSans-Bold.ttf (Noto Sans Bold, Latin only;\n// core/fonts/OFL.txt). Run it again instead of editing this file.\nexport const NOTO_SANS_BOLD_BASE64 =\n  "${font.toString("base64")}";\n`,
);
console.log(`wrote ${out} (${font.byteLength} bytes of font)`);
